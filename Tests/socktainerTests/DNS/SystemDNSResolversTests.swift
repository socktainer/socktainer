import Foundation
import Testing

@testable import socktainer

@Suite("SystemDNSResolvers")
struct SystemDNSResolversTests {
    @Test("Dynamic store ServerAddresses are returned in order as IPv4 upstreams")
    func dynamicStore() {
        let dict: [String: Any] = ["ServerAddresses": ["10.0.0.2", "192.168.1.1"], "DomainName": "corp.example"]
        #expect(
            SystemDNSResolvers.resolvers(fromDynamicStore: dict) == [
                DNSUpstream(host: "10.0.0.2", port: 53), DNSUpstream(host: "192.168.1.1", port: 53),
            ])
    }

    @Test("IPv6, unusable, invalid and duplicate addresses are dropped")
    func dynamicStoreFilters() {
        let dict: [String: Any] = [
            "ServerAddresses": ["fe80::1%en0", "2001:4860:4860::8888", "0.0.0.0", "dns.example.com", "10.0.0.2", "10.0.0.2", "1.1.1.1"]
        ]
        #expect(
            SystemDNSResolvers.resolvers(fromDynamicStore: dict) == [
                DNSUpstream(host: "10.0.0.2", port: 53), DNSUpstream(host: "1.1.1.1", port: 53),
            ])
    }

    @Test("Missing or malformed ServerAddresses yield no resolvers")
    func dynamicStoreMissing() {
        #expect(SystemDNSResolvers.resolvers(fromDynamicStore: [:]).isEmpty)
        #expect(SystemDNSResolvers.resolvers(fromDynamicStore: ["ServerAddresses": 42]).isEmpty)
    }

    @Test("resolv.conf nameserver lines are extracted in order")
    func resolvConf() {
        let text = """
            # Generated by NetworkConfiguration
            domain corp.example
            search corp.example
            nameserver 10.0.0.2
            nameserver\t192.168.1.1
            nameserver fe80::1%en0
            nameserver 10.0.0.2
            options timeout:2
            """
        #expect(
            SystemDNSResolvers.resolvers(fromResolvConf: text) == [
                DNSUpstream(host: "10.0.0.2", port: 53), DNSUpstream(host: "192.168.1.1", port: 53),
            ])
    }

    @Test("resolv.conf without nameservers yields none")
    func resolvConfEmpty() {
        #expect(SystemDNSResolvers.resolvers(fromResolvConf: "").isEmpty)
        #expect(SystemDNSResolvers.resolvers(fromResolvConf: "nameserver\n# nameserver 1.1.1.1").isEmpty)
    }

    @Test("Watcher reports at start and stops cleanly")
    func watcherLifecycle() {
        final class Calls: @unchecked Sendable {
            private let lock = NSLock()
            private var _count = 0
            func record() { lock.withLock { _count += 1 } }
            var count: Int { lock.withLock { _count } }
        }
        let calls = Calls()
        let watcher = SystemDNSResolverWatcher { _ in calls.record() }
        watcher.start()
        #expect(calls.count >= 1)
        watcher.start()  // idempotent
        watcher.stop()
        watcher.stop()  // idempotent
    }
}
